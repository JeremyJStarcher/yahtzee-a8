def write_p2s_xlate(filename="p2s_xlate.inc") -> None:
    """
    Write a 6502 assembly translation table mapping print codes to screen codes.

    For each byte value ``i`` treated as a print-order index (0..n-1), finds the
    :class:`FontChar` whose ``print_order == i`` and writes that character's
    ``screen_order`` as a ``.DB`` byte.

    Args:
        filename: Output path for the generated include file.
                  Defaults to ``"p2s_xlate.inc"`` in the current directory.
    """
    # Build lookup: print_order -> screen_order
    p2s_map: dict[int, int] = {}
    for char in FONT_DATA:
        if 0 <= char.print_order < len(FONT_DATA):
            p2s_map[char.print_order] = char.screen_order

    n = len(FONT_DATA)

    with open(filename, "w", encoding="utf-8") as f:
        f.write("; Translation table: print_code -> screen_code\n")
        f.write(f"; Generated from {len(FONT_DATA)} font characters\n")
        f.write(";\n")

        values_per_line = 16
        values: list[str] = []

        for i in range(n):
            sc = p2s_map.get(i, 0x20)  # Default to space ($20) if unmapped
            values.append(f"${sc:02X}")

            if (i + 1) % values_per_line == 0 or i == n - 1:
                f.write(".byte " + ", ".join(values))
                f.write("\n")
                values.clear()


def _assign_orders() -> None:
    """Assign screen_order and print_order to all font characters.

    **Data-generation utility only.**  This function was used to populate the
    ``print_order`` and ``screen_order`` fields in the hard-coded ``FONT_DATA``
    table above.  It is not called during normal emulator operation and is
    retained only for documentation / reproducibility of the initial ordering.
    """
    n = len(FONT_DATA)

    # Generate random screen order (permutation of 0..n-1)
    screen_indices = list(range(n))
    random.shuffle(screen_indices)

    for i, char in enumerate(FONT_DATA):
        char.screen_order = screen_indices[i]
        char.print_order = -1


    # Assign print_order for ASCII printable characters (0x20-0x7F).
    # Their print_order matches their screen_order.
    used_print_orders: set[int] = set()

    for char in FONT_DATA:
        if 0x20 <= char.codepoint < 0x80:
            char.print_order = char.codepoint
            used_print_orders.add(char.codepoint)

    # Assign remaining print_orders from unused slots.
    available = [i for i in range(n) if i not in used_print_orders]
    random.shuffle(available)

    it = iter(available)
    for char in FONT_DATA:
        if char.print_order == -1:
            char.print_order = next(it)


